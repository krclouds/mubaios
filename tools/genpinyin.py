"""Generate src/pinyin.h: syllable -> up to 9 common characters.

Sources:
  * Unihan kMandarin readings (tone marks stripped) for the pronunciation.
  * GB2312 level 1 (3755 most common characters) as the character set, so the
    candidate lists stay short and useful.
"""
import io
import os
import re
import unicodedata
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "pinyin.h")
CACHE = os.path.join(ROOT, "cache", "Unihan.zip")

COMMON = ("的一是了我不人在他有这个上们来到时大地为子中你说生国年着就那和要她出也得里后自以会家可下而过天去能对小多然于心学么之都好看起发当没成只如事把还用第样道想作种开美总从无情己面最女但现前些所同日手又行意动方期它头经长儿回位分爱老因很给名法间斯知世什两次使身者被高已亲其进此话常与活正感")


def load_unihan():
    if not os.path.exists(CACHE):
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        req = urllib.request.Request(
            "https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip",
            headers={"User-Agent": "python"})
        data = urllib.request.urlopen(req, timeout=90).read()
        open(CACHE, "wb").write(data)
    z = zipfile.ZipFile(CACHE)
    text = z.read("Unihan_Readings.txt").decode("utf-8", "ignore")
    readings = {}
    for line in text.splitlines():
        if "\tkMandarin\t" not in line:
            continue
        code, _, val = line.split("\t", 2)
        cp = int(code[2:], 16)
        readings.setdefault(cp, val.split()[0])
    return readings


def strip_tone(s):
    for a, b in {"ü": "v", "ǖ": "v", "ǘ": "v", "ǚ": "v", "ǜ": "v"}.items():
        s = s.replace(a, b)
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.replace("ü", "v").replace("Ü", "v")
    return re.sub(r"[^a-z]", "", s.lower())


def gb2312_level1():
    out = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            out.append(ch)
    return out


def main():
    readings = load_unihan()
    priority = {}
    for ch in COMMON:
        py = readings.get(ord(ch))
        if not py:
            continue
        priority.setdefault(strip_tone(py), []).append(ch)

    groups = {}
    for ch in gb2312_level1():
        py = readings.get(ord(ch))
        if not py:
            continue
        py = strip_tone(py)
        if not py:
            continue
        groups.setdefault(py, [])
        if len(groups[py]) < 9 and ch not in groups[py]:
            groups[py].append(ch)

    for py in groups:
        groups[py] = priority.get(py, []) + [c for c in groups[py] if c not in priority.get(py, [])]
        groups[py] = groups[py][:9]

    lines = [
        "/* generated by tools/genpinyin.py -- pinyin syllable -> candidates */",
        "struct pinyin_entry { const char *py; const char *chars; };",
        "static const struct pinyin_entry pinyin_table[] = {",
    ]
    for py in sorted(groups):
        chars = "".join(groups[py])
        lines.append('\t{"%s", "%s"},' % (py, chars))
    lines.append("};")
    lines.append("#define PINYIN_N (int)(sizeof(pinyin_table) / sizeof(pinyin_table[0]))")
    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("syllables:", len(groups), "->", OUT)


if __name__ == "__main__":
    main()
