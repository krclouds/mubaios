#!/usr/bin/env python3
"""Generate the bitmap fonts used by the NovaOS UI.

  src/font8x16.h  -- ASCII 32..126, 8x16
  src/font_cjk.h  -- every CJK character used in the sources, 16x16

Both are rendered once here and committed as C data, so the guest needs no font
files and no font library.  Re-run after adding new Chinese strings.
"""
import os
import re

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src")

OPEN = os.path.join(ROOT, "cache", "fonts")

ASCII_FONTS = [
    os.path.join(OPEN, "DejaVuSansMono.ttf"),
    r"C:\Windows\Fonts\consola.ttf",
    r"C:\Windows\Fonts\cour.ttf",
]
CJK_FONTS = [
    os.path.join(OPEN, "NotoSansCJKsc-Regular.otf"),
    r"C:\Windows\Fonts\msyh.ttc",
    r"C:\Windows\Fonts\simhei.ttf",
    r"C:\Windows\Fonts\simsun.ttc",
]

W, H = 8, 16
CW, CH = 16, 16
FIRST, LAST = 32, 126

# Extra characters that may appear at runtime (file names, dates, punctuation).
EXTRA = ("年月日星期一二三四五六七八九十设置文件画板终端关于显示已安装应用关机内核架构帧缓冲内存根系统"
         "欢迎回来没有最近的应用程序分辨率像素格式触摸屏返回桌面清空绘制输入命令回车执行试试"
         "错误未知目录空查看器二进制或位图大小正在启动请稍候，。：、（）【】—…“”‘’！？")


def render(font, ch, cell_w, cell_h):
    img = Image.new("L", (cell_w, cell_h), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), ch, font=font)
    x = (cell_w - (bbox[2] - bbox[0])) // 2 - bbox[0]
    y = (cell_h - (bbox[3] - bbox[1])) // 2 - bbox[1]
    draw.text((x, y), ch, fill=255, font=font)
    return img


def gen_ascii(path):
    font_path = next(p for p in ASCII_FONTS if os.path.exists(p))
    font = ImageFont.truetype(font_path, 14)
    rows_all = []
    for code in range(FIRST, LAST + 1):
        img = render(font, chr(code), W, H)
        rows = []
        for row in range(H):
            bits = 0
            for col in range(W):
                if img.getpixel((col, row)) > 110:
                    bits |= 0x80 >> col
            rows.append(bits)
        rows_all.append(rows)

    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/genfont.py -- 8x16 ASCII font */\n")
        f.write("static const unsigned char font8x16[%d][%d] = {\n" % (len(rows_all), H))
        for rows in rows_all:
            f.write("    {" + ",".join("0x%02x" % b for b in rows) + "},\n")
        f.write("};\n")
    print("ascii glyphs:", len(rows_all))


def collect_chars():
    chars = set(EXTRA)
    for name in os.listdir(SRC):
        if not name.endswith((".c", ".h")):
            continue
        text = open(os.path.join(SRC, name), encoding="utf-8", errors="ignore").read()
        chars.update(re.findall(r"[\u3000-\u9fff\uff00-\uffef]", text))
    return sorted(c for c in chars if ord(c) >= 0x80)


def gen_cjk(path):
    chars = collect_chars()
    font_path = next(p for p in CJK_FONTS if os.path.exists(p))
    font = ImageFont.truetype(font_path, 15)

    glyphs = []
    for ch in chars:
        img = render(font, ch, CW, CH)
        rows = []
        for row in range(CH):
            bits = 0
            for col in range(CW):
                if img.getpixel((col, row)) > 90:
                    bits |= 0x8000 >> col
            rows.append(bits)
        glyphs.append((ord(ch), rows))

    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/genfont.py -- 16x16 CJK font (%d glyphs) */\n" % len(glyphs))
        f.write("struct cjk_glyph { unsigned int cp; unsigned short rows[%d]; };\n" % CH)
        f.write("static const struct cjk_glyph cjk_glyphs[%d] = {\n" % len(glyphs))
        for cp, rows in glyphs:
            f.write("    {0x%04x, {" % cp + ",".join("0x%04x" % r for r in rows) + "}},\n")
        f.write("};\n")
        f.write("static const int cjk_glyph_count = %d;\n" % len(glyphs))
    print("cjk glyphs:", len(glyphs), "font:", os.path.basename(font_path))


if __name__ == "__main__":
    gen_ascii(os.path.join(SRC, "font8x16.h"))
    gen_cjk(os.path.join(SRC, "font_cjk.h"))
